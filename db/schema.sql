-- ---------------------------------------------------------------------------
-- 1. Base Table: health_data
--    Stores raw telemetry received from ESP32 or simulator.
-- ---------------------------------------------------------------------------
create table if not exists public.health_data (
    id              bigint generated by default as identity primary key,
    device_id       text not null default 'esp32-01',
    created_at      timestamptz not null default now(),
    bpm             integer,
    spo2            double precision,
    temperature     double precision,
    movement        boolean default false,
    raw_pulse       integer,
    finger_detected boolean,
    accel_x         real,
    accel_y         real,
    accel_z         real,
    gyro_x          real,
    gyro_y          real,
    gyro_z          real,
    hr_valid        boolean,
    spo2_valid      boolean
);

-- Ensure all columns exist if migrating from an earlier minimal table
alter table public.health_data
    add column if not exists device_id  text not null default 'esp32-01',
    add column if not exists raw_pulse       integer,
    add column if not exists finger_detected boolean,
    add column if not exists accel_x    real,
    add column if not exists accel_y    real,
    add column if not exists accel_z    real,
    add column if not exists gyro_x     real,
    add column if not exists gyro_y     real,
    add column if not exists gyro_z     real,
    add column if not exists hr_valid   boolean,
    add column if not exists spo2_valid boolean;

-- Derived acceleration magnitude for fall detection
do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'health_data'
          and column_name = 'accel_magnitude'
    ) then
        alter table public.health_data
            add column accel_magnitude real generated always as (
                case
                    when accel_x is null or accel_y is null or accel_z is null
                        then null
                    else sqrt(accel_x * accel_x
                            + accel_y * accel_y
                            + accel_z * accel_z)
                end
            ) stored;
    end if;
end$$;

create index if not exists health_data_device_time_idx
    on public.health_data (device_id, created_at desc);

create index if not exists health_data_time_idx
    on public.health_data (created_at desc);

-- ---------------------------------------------------------------------------
-- 2. devices: One row per patient node
-- ---------------------------------------------------------------------------
create table if not exists public.devices (
    device_id     text primary key,
    patient_name  text,
    patient_age   int,
    ward          text,
    registered_at timestamptz not null default now(),
    last_seen_at  timestamptz
);

insert into public.devices (device_id, patient_name, ward)
values 
    ('esp32-01', 'Demo Patient', 'General Ward'),
    ('esp8266-01', 'Legacy Node', 'General Ward')
on conflict (device_id) do nothing;

-- ---------------------------------------------------------------------------
-- 3. alerts: Emitted by the deterministic clinical rule/trend engine
-- ---------------------------------------------------------------------------
do $$
begin
    if not exists (select 1 from pg_type where typname = 'alert_severity') then
        create type alert_severity as enum ('normal', 'warning', 'critical');
    end if;
end$$;

create table if not exists public.alerts (
    id              bigserial primary key,
    device_id       text not null default 'esp32-01',
    created_at      timestamptz not null default now(),
    severity        alert_severity not null,
    metric          text not null,          -- heart_rate | spo2 | temperature_c | fall
    value           numeric,                -- the reading that tripped the rule
    rule            text not null,          -- rule identifier
    message         text not null,          -- human-readable summary
    reading_id      bigint,                 -- health_data.id reference
    acknowledged    boolean not null default false,
    acknowledged_at timestamptz
);

create index if not exists alerts_device_time_idx
    on public.alerts (device_id, created_at desc);

create index if not exists alerts_open_idx
    on public.alerts (device_id, acknowledged, created_at desc);

-- ---------------------------------------------------------------------------
-- 4. ai_summaries: Cached Generative AI interpretations
-- ---------------------------------------------------------------------------
create table if not exists public.ai_summaries (
    id            bigserial primary key,
    device_id     text not null default 'esp32-01',
    created_at    timestamptz not null default now(),
    window_start  timestamptz not null,
    window_end    timestamptz not null,
    status        alert_severity not null,
    summary       text not null,
    headline      text,
    model         text,
    input_digest  jsonb,
    latency_ms    int
);

create index if not exists ai_summaries_device_time_idx
    on public.ai_summaries (device_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 5. Normalised view: readings_v
--    Maps firmware columns (bpm, temperature, created_at) to clinical names.
-- ---------------------------------------------------------------------------
create or replace view public.readings_v as
select
    id,
    device_id,
    created_at                          as recorded_at,
    nullif(bpm, 0)                      as heart_rate,
    spo2,
    temperature                         as temperature_c,
    movement,
    raw_pulse,
    finger_detected,
    accel_x, accel_y, accel_z,
    gyro_x,  gyro_y,  gyro_z,
    hr_valid,
    spo2_valid,
    -- appended last: create or replace view can only add columns at the end
    accel_magnitude
from public.health_data;

-- ---------------------------------------------------------------------------
-- 6. Realtime publication: Allows React dashboard to receive live inserts
-- ---------------------------------------------------------------------------
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and tablename = 'health_data'
    ) then
        alter publication supabase_realtime add table public.health_data;
    end if;

    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and tablename = 'alerts'
    ) then
        alter publication supabase_realtime add table public.alerts;
    end if;
exception
    when undefined_object then
        raise notice 'supabase_realtime publication not found - skipping';
end$$;

-- ---------------------------------------------------------------------------
-- 7. Row Level Security (RLS)
--    Enables anonymous read/write access for frontend & direct device streams.
-- ---------------------------------------------------------------------------
alter table public.health_data  enable row level security;
alter table public.alerts       enable row level security;
alter table public.ai_summaries enable row level security;
alter table public.devices      enable row level security;

drop policy if exists "anon read health_data"  on public.health_data;
drop policy if exists "anon write health_data" on public.health_data;
drop policy if exists "anon read alerts"       on public.alerts;
drop policy if exists "anon read ai_summaries" on public.ai_summaries;
drop policy if exists "anon read devices"      on public.devices;

create policy "anon read health_data"  on public.health_data  for select using (true);
create policy "anon write health_data" on public.health_data  for insert with check (true);
create policy "anon read alerts"       on public.alerts       for select using (true);
create policy "anon read ai_summaries" on public.ai_summaries for select using (true);
create policy "anon read devices"      on public.devices      for select using (true);

-- ---------------------------------------------------------------------------
-- 8. Table: health_readings (Raw ESP32 sensor stream without IMU)
-- ---------------------------------------------------------------------------
create table if not exists public.health_readings (
    id              bigint generated by default as identity primary key,
    device_id       text not null default 'esp32-01',
    created_at      timestamptz not null default now(),
    raw_pulse       integer not null,
    finger_detected boolean not null,
    heart_rate      integer not null,
    spo2            integer not null,
    temperature_c   double precision not null
);

alter table public.health_readings enable row level security;

drop policy if exists "Allow ESP32 health data inserts" on public.health_readings;
drop policy if exists "Allow anon read health_readings" on public.health_readings;

create policy "Allow ESP32 health data inserts"
    on public.health_readings for insert to anon, authenticated with check (true);

create policy "Allow anon read health_readings"
    on public.health_readings for select to anon, authenticated using (true);

do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and tablename = 'health_readings'
    ) then
        alter publication supabase_realtime add table public.health_readings;
    end if;
exception
    when others then null;
end$$;

-- Auto-sync trigger from health_readings to health_data and devices
create or replace function public.sync_health_readings_to_health_data()
returns trigger as $$
begin
    insert into public.health_data (
        device_id,
        created_at,
        bpm,
        spo2,
        temperature,
        movement,
        hr_valid,
        spo2_valid,
        raw_pulse,
        finger_detected
    ) values (
        'esp32-01',
        new.created_at,
        new.heart_rate,
        new.spo2,
        new.temperature_c,
        false,
        new.finger_detected,
        new.finger_detected,
        new.raw_pulse,
        new.finger_detected
    );

    update public.devices
    set last_seen_at = new.created_at
    where device_id = 'esp32-01';

    return new;
end;
$$ language plpgsql;

drop trigger if exists trg_sync_health_readings on public.health_readings;
create trigger trg_sync_health_readings
after insert on public.health_readings
for each row
execute function public.sync_health_readings_to_health_data();

